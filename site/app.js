  "use strict";

  var D = window.SITE_DATA;
  var SVGNS = "http://www.w3.org/2000/svg";
  var $ = function (sel, root) { return (root || document).querySelector(sel); };

  // ---------- tiny DOM helpers (text always via textContent / text nodes) ----------
  function apply(node, props, kids) {
    Object.keys(props || {}).forEach(function (k) {
      var v = props[k];
      if (v === undefined || v === null || v === false) return;
      if (k === "text") node.textContent = v;
      else if (k === "on") Object.keys(v).forEach(function (ev) { node.addEventListener(ev, v[ev]); });
      else node.setAttribute(k, v === true ? "" : v);
    });
    kids.forEach(function (kid) {
      [].concat(kid).forEach(function (x) {
        if (x === null || x === undefined || x === false) return;
        node.append(x.nodeType ? x : document.createTextNode(String(x)));
      });
    });
    return node;
  }
  function h(tag, props) { return apply(document.createElement(tag), props, [].slice.call(arguments, 2)); }
  function sv(tag, props) { return apply(document.createElementNS(SVGNS, tag), props, [].slice.call(arguments, 2)); }
  function icon(name) { return h("i", { "class": "ph ph-" + name, "aria-hidden": "true" }); }

  var pct = function (x, d) { return (x * 100).toFixed(d || 0) + "%"; };
  var sgn = function (v, d) { var n = Math.abs(v).toFixed(d === undefined ? 1 : d); return (v > 0 ? "+" : v < 0 ? "-" : "") + n; };
  var plural = function (n, one, many) { return n + " " + (n === 1 ? one : many); };
  var SIDE_NAME = { bull: "Bull", bear: "Bear", tie: "Tie" };
  var VERDICT = { bull: "Bull wins", bear: "Bear wins", tie: "Tie" };

  // ---------- tooltip: one shared element, enhances but never gates ----------
  var tip = $("#tip");
  function showTip(lines, x, y) {
    tip.replaceChildren.apply(tip, lines.map(function (l) { return h("div", { "class": l.c || "", text: l.t }); }));
    tip.hidden = false;
    var r = tip.getBoundingClientRect();
    var left = x + 14, top = y + 16;
    if (left + r.width > window.innerWidth - 8) left = x - r.width - 14;
    if (top + r.height > window.innerHeight - 8) top = y - r.height - 16;
    tip.style.left = Math.max(8, left) + "px";
    tip.style.top = Math.max(8, top) + "px";
  }
  function hideTip() { tip.hidden = true; }
  function bindTip(node, lines) {
    var get = typeof lines === "function" ? lines : function () { return lines; };
    node.addEventListener("pointermove", function (e) { showTip(get(), e.clientX, e.clientY); });
    node.addEventListener("pointerleave", hideTip);
    node.addEventListener("focus", function () {
      var r = node.getBoundingClientRect();
      showTip(get(), r.left + r.width / 2, r.top + r.height / 2);
    });
    node.addEventListener("blur", hideTip);
  }

  // ---------- theme ----------
  function currentTheme() {
    return document.documentElement.dataset.theme ||
      (window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light");
  }
  function syncThemeIcon() {
    var dark = currentTheme() === "dark";
    var btn = $("#theme");
    btn.replaceChildren(icon(dark ? "sun" : "moon"));
    btn.setAttribute("aria-label", dark ? "Switch to light theme" : "Switch to dark theme");
  }
  $("#theme").addEventListener("click", function () {
    var next = currentTheme() === "dark" ? "light" : "dark";
    document.documentElement.dataset.theme = next;
    try { localStorage.setItem("theme", next); } catch (e) { /* private mode: fine */ }
    syncThemeIcon();
  });
  syncThemeIcon();

  // ---------- reveal on scroll (only when motion is allowed) ----------
  var io = "IntersectionObserver" in window ? new IntersectionObserver(function (entries) {
    entries.forEach(function (en) { if (en.isIntersecting) { en.target.classList.add("in"); io.unobserve(en.target); } });
  }, { threshold: 0.12 }) : null;
  function reveal(node) {
    node.classList.add("reveal");
    if (io) io.observe(node); else node.classList.add("in");
  }

  // ---------- chart card: title, chart, table twin, redraw on resize ----------
  function mountChart(host, opts) {
    if (host._ro) host._ro.disconnect();
    host.replaceChildren();
    var tblBtn = h("button", { "class": "tbl-btn", type: "button", "aria-pressed": "false" }, icon("table"), "Table");
    var body = h("div", { "class": "body" });
    var tbl = h("div", { "class": "tbl" });
    host.append(
      h("div", { "class": "top" },
        h("div", {}, h("h3", { text: opts.title }), opts.sub ? h("p", { "class": "sub", text: opts.sub }) : null),
        opts.table ? tblBtn : null),
      body, tbl);
    if (opts.legend) host.append(opts.legend);

    var lastW = 0;
    function render() { body.replaceChildren(); opts.draw(body, body.clientWidth || 600); }
    host._ro = new ResizeObserver(function () {
      var w = body.clientWidth;
      if (w && Math.abs(w - lastW) > 1) { lastW = w; render(); }
    });
    host._ro.observe(body);
    render();

    if (opts.table) {
      var built = false;
      tblBtn.addEventListener("click", function () {
        var on = host.classList.toggle("show-table");
        tblBtn.setAttribute("aria-pressed", String(on));
        tblBtn.replaceChildren(icon(on ? "chart-bar" : "table"), on ? "Chart" : "Table");
        if (on && !built) {
          var t = opts.table();
          tbl.append(h("table", {},
            h("thead", {}, h("tr", {}, t.head.map(function (c) { return h("th", { scope: "col", text: c }); }))),
            h("tbody", {}, t.rows.map(function (r) { return h("tr", {}, r.map(function (c) { return h("td", { text: String(c) }); })); }))));
          built = true;
        }
      });
    }
  }

