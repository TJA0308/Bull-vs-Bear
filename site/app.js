  (function how() {
    var m = D.meta, P = D.prompts;
    function peek(label, text) {
      return h("details", { "class": "peek" }, h("summary", {}, label, icon("caret-down")), h("pre", { text: text }));
    }
    var steps = [
      { t: "Fetch", p: "Looks the company up on SEC EDGAR, finds its latest 10-K, and downloads it once. The file is cached so reruns do not hit the SEC again." },
      { t: "Extract", p: "Pulls out Item 1A (risk factors) and Item 7 (management's discussion) as plain text. Filings write their headings in different ways, so the patterns tolerate dashes, periods and words split across tags." },
      { t: "Debate", p: "The bull and the bear each read the extracted text, argue for two rounds, and back every claim with a word-for-word quote.",
        stat: "About " + plural(m.callsPerDebate, "model call", "model calls") + " and " + Math.round(m.tokensInPerDebate / 1000) + "k input tokens per debate, roughly $" + m.costPerDebate.toFixed(2) + ".",
        peeks: [["Bull instructions", P.bull + "\n\n" + P.outputFormat], ["Bear instructions", P.bear + "\n\n" + P.outputFormat]] },
      { t: "Verify", p: "Plain Python checks each quote against the filing. An exact match passes at once. Anything else gets a fuzzy score, and quotes under five words are rejected.",
        peeks: [["The checker's code", D.code.normalize + "\n\n" + D.code.verify]] },
      { t: "Judge", p: "A final call scores both sides on evidence, logic and responsiveness. It is told which quotes were not verified, and that speaking first or last is not a reason to win.",
        peeks: [["Judge instructions", P.judge]] }
    ];
    var list = $("#steps");
    steps.forEach(function (s) {
      var right = h("div", {}, h("p", { text: s.p }));
      if (s.stat) right.append(h("p", { "class": "stat", text: s.stat }));
      (s.peeks || []).forEach(function (pk) { right.append(peek(pk[0], pk[1])); });
      list.append(h("li", { "class": "step" }, h("h3", { text: s.t }), right));
    });

    var limits = [
      ["A small test", cap(word(m.debates)) + " companies, one debate each per setup." + (D.bias.noise ? " Debating the same companies again moved the bear's share of judgments by " + Math.round(D.bias.noise.noiseGap) + " points, so each percentage is one draw, not a precise measurement." + (D.bias.repeats ? " Across " + word(D.bias.repeats.nFull) + " repeats of the same input, the bear's share ranged from " + Math.min.apply(null, D.bias.repeats.bearShare.full) + "% to " + Math.max.apply(null, D.bias.repeats.bearShare.full) + "%." : "") : " The percentages are rough estimates, not precise measurements.")],
      ["One model family", "The debaters are " + modelName(D.model) + (D.bias.judges ? ", and the two judges compared are " + modelName(D.bias.judges.firstModel) + " and " + modelName(D.bias.judges.secondModel) : ", and so is the judge") + ". All Claude models, so a bias shared across the family is untested, and there is no answer key to say which judge is right."],
      ["Listing order scrambles the dialogue", "When the judge lists the side that spoke second first, it reads a reply before the argument it answers. The listing-order results mix pure position bias with that effect." + (D.bias.chrono ? " Re-judging the debates in speaking order gave similar bear shares, so this did not create the bear's edge." : "")],
      ["Quotes are checked, not claims", "The checker proves the words (and numbers) are in the filing. It cannot tell whether the quote really supports the claim built on it, and a one-word wording change can still pass."],
      ["Banks are skipped", "Banks such as JPMorgan keep their MD&A in a separate exhibit, so the extractor rejects them instead of guessing."],
      ["No stock predictions", "This shows how arguments are made and judged. It says nothing about whether a stock will go up or down."]
    ];
    var limBox = $("#limits");
    limBox.append.apply(limBox, limits.map(function (l) { return h("div", {}, h("h3", { text: l[0] }), h("p", { text: l[1] })); }));
    $("#built").append(h("strong", { text: "Built with " }),
      "Python, the Claude API, SEC EDGAR, BeautifulSoup, RapidFuzz and pytest. This page is plain HTML, CSS and JavaScript generated from the saved results by build_site.py, and hosted on GitHub Pages.");
  })();

