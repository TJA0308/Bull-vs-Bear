  var VERDICT = { bull: "Bull wins", bear: "Bear wins", tie: "Tie" };

  // ---------- tooltip: one shared element, enhances but never gates ----------
  var tip = $("#tip");
  function showTip(lines, x, y) {
    tip.replaceChildren.apply(tip, lines.map(function (l) { return h("div", { "class": l.c || "", text: l.t }); }));
    tip.hidden = false;
    var r = tip.getBoundingClientRect();
    var left = x + 14, top = y + 16;
    if (left + r.width > window.innerWidth - 8) left = x - r.width - 14;
    if (top + r.height > window.innerHeight - 8) top = y - r.height - 16;
    tip.style.left = Math.max(8, left) + "px";
    tip.style.top = Math.max(8, top) + "px";
  }
  function hideTip() { tip.hidden = true; }
  function bindTip(node, lines) {
    var get = typeof lines === "function" ? lines : function () { return lines; };
    node.addEventListener("pointermove", function (e) { showTip(get(), e.clientX, e.clientY); });
    node.addEventListener("pointerleave", hideTip);
    node.addEventListener("focus", function () {
      var r = node.getBoundingClientRect();
      showTip(get(), r.left + r.width / 2, r.top + r.height / 2);
    });
    node.addEventListener("blur", hideTip);
  }

  // ---------- theme ----------
  function currentTheme() {
    return document.documentElement.dataset.theme ||
      (window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light");
  }
  function syncThemeIcon() {
    var dark = currentTheme() === "dark";
    var btn = $("#theme");
    btn.replaceChildren(icon(dark ? "sun" : "moon"));
    btn.setAttribute("aria-label", dark ? "Switch to light theme" : "Switch to dark theme");
  }
  $("#theme").addEventListener("click", function () {
    var next = currentTheme() === "dark" ? "light" : "dark";
    document.documentElement.dataset.theme = next;
    try { localStorage.setItem("theme", next); } catch (e) { /* private mode: fine */ }
    syncThemeIcon();
  });
