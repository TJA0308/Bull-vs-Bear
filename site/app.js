  var state = { ticker: tickers.indexOf("AAPL") >= 0 ? "AAPL" : tickers[0], order: "base" };

  function debateFor(ticker, order) {
    var set = order === "bearFirst" ? D.debates.bearFirst : D.debates.base;
    return set && set[ticker] ? set[ticker] : null;
  }

  function renderFilters() {
    var box = $("#debate-filters");
    box.replaceChildren();
    var chips = h("div", { "class": "chips", role: "group", "aria-label": "Company" }, tickers.map(function (t) {
      return h("button", { "class": "chip", type: "button", "aria-pressed": String(t === state.ticker), text: t,
        title: base[t].name, on: { click: function () { state.ticker = t; if (!debateFor(t, state.order)) state.order = "base"; renderFilters(); renderDebate(); } } });
    }));
    var hasVariant = !!debateFor(state.ticker, "bearFirst");
    var order = h("div", { "class": "chips", role: "radiogroup", "aria-label": "Who speaks first" },
      [["base", "Bull speaks first"], ["bearFirst", "Bear speaks first"]].map(function (o) {
        var disabled = o[0] === "bearFirst" && !hasVariant;
        return h("button", { "class": "chip", type: "button", role: "radio", "aria-checked": String(state.order === o[0]),
          disabled: disabled, text: o[1], title: disabled ? "Not run for this company" : null,
          on: { click: function () { state.order = o[0]; renderFilters(); renderDebate(); } } });
      }));
    box.append(chips, h("span", { "class": "sep", "aria-hidden": "true" }), h("span", { "class": "label", text: "Who speaks first:" }), order);
  }

  function badge(claim) {
    var ok = claim.verified;
    return h("span", { "class": "badge " + (ok ? "ok" : "no") }, icon(ok ? "check-circle" : "x-circle"),
      (ok ? "Verified " : "Not verified ") + Math.round(claim.score));
  }

  function claimEl(claim) {
    var src = h("div", { "class": "src" });
    var btn = h("button", { "class": "src-btn", type: "button", "aria-expanded": "false" }, "Source", icon("caret-down"));
    btn.addEventListener("click", function () {
      var open = src.classList.toggle("open");
      btn.setAttribute("aria-expanded", String(open));
      if (open && !src.childNodes.length) {
        src.append(h("div", { "class": "cap", text: "Quote used by the agent" }),
          h("p", { "class": "quote", text: "“" + claim.quote + "”" }));
        if (claim.ctx) {
          src.append(h("div", { "class": "cap", text: claim.verified ? "Where it appears in the filing" : "Closest passage in the filing (match " + Math.round(claim.score) + " of 100)" }),
            h("p", { "class": "quote" }, "…" + claim.ctx.pre + " ", h("mark", { text: claim.ctx.match }), " " + claim.ctx.post + "…"));
        } else {
          src.append(h("div", { "class": "cap", text: "No close passage to show for this quote." }));
        }
      }
    });
    return h("li", { "class": "claim" },
      h("div", { "class": "row" }, h("p", { "class": "text", text: claim.claim }), h("div", { "class": "tools" }, badge(claim), btn)), src);
  }

  function turnEl(side, turn, first) {
    return h("article", { "class": "turn" },
      h("div", { "class": "who" }, h("span", { "class": "side-dot " + side }), SIDE_NAME[side] + " analyst",
        h("span", { "class": "sub", text: first ? "opens the round" : "replies" })),
      h("p", { "class": "arg", text: turn.argument }),
      h("ul", { "class": "claims" }, turn.claims.map(claimEl)));
  }

  function runDots(rows, listed) {
    var runs = rows[listed === "bull" ? "bullListedFirst" : "bearListedFirst"];
    return h("div", { "class": "run-group" }, h("span", { text: SIDE_NAME[listed] + " listed first" }),
      runs.map(function (r, i) {
        var dot = h("span", { "class": "run-dot " + r.w, tabindex: "0", role: "img", "aria-label": "Run " + (i + 1) + ": " + VERDICT[r.w] });
        bindTip(dot, [{ t: VERDICT[r.w], c: "tv" }, { t: "Run " + (i + 1) + ", " + SIDE_NAME[listed] + " listed first" }, { t: "Bull minus bear: " + sgn(r.m, 0) + " points" }]);
        return dot;
      }));
  }

  function drawDumbbell(body, w, scores) {
    var rows = [["Evidence", "evidence"], ["Logic", "logic"], ["Responsiveness", "responsiveness"]];
    var labelW = Math.min(112, w * 0.34), padR = 22, rowH = 42, top = 6, axisH = 26;
    var H = top + rows.length * rowH + axisH;
    var x = function (v) { return labelW + (v / 10) * (w - labelW - padR); };
    var svg = sv("svg", { width: w, height: H, role: "img", "aria-label": "Judge scores out of 10 for each side, by criterion" });
    [0, 2, 4, 6, 8, 10].forEach(function (t) {
      svg.append(sv("line", { "class": t === 0 ? "axis-line" : "grid-line", x1: x(t), x2: x(t), y1: top, y2: top + rows.length * rowH }),
        sv("text", { x: x(t), y: H - 6, "text-anchor": "middle", text: String(t) }));
    });
    rows.forEach(function (r, i) {
      var y = top + i * rowH + rowH / 2;
      var b = scores.bull[r[1]], e = scores.bear[r[1]];
      var same = b === e;
      svg.append(sv("text", { x: 0, y: y + 4, text: r[0], style: "fill:var(--ink)" }),
        sv("line", { x1: x(Math.min(b, e)), x2: x(Math.max(b, e)), y1: y, y2: y, stroke: "var(--axis)", "stroke-width": 2, "stroke-linecap": "round" }),
        sv("circle", { cx: x(e), cy: same ? y + 5 : y, r: 6, "class": "ring", style: "fill:var(--bear)" }),
        sv("circle", { cx: x(b), cy: same ? y - 5 : y, r: 6, "class": "ring", style: "fill:var(--bull)" }));
      var hi = Math.max(b, e), lo = Math.min(b, e);
      if (same) svg.append(sv("text", { x: x(b) + 12, y: y + 4, text: b + " each", style: "fill:var(--ink)" }));
      else svg.append(
        sv("text", { x: x(hi) + 11, y: y + 4, "text-anchor": "start", text: String(hi), style: "fill:var(--ink);font-weight:650" }),
        sv("text", { x: x(lo) - 11, y: y + 4, "text-anchor": "end", text: String(lo), style: "fill:var(--ink);font-weight:650" }));
      var hit = sv("rect", { x: 0, y: top + i * rowH, width: w, height: rowH, fill: "transparent", tabindex: "0",
        "aria-label": r[0] + ": bull " + b + ", bear " + e });
      bindTip(hit, [{ t: r[0], c: "tv" }, { t: "Bull: " + b + " of 10" }, { t: "Bear: " + e + " of 10" }]);
      svg.append(hit);
    });
    body.append(svg);
  }

  function renderPanel(d) {
    var panel = $("#panel");
    panel.replaceChildren();
    var j = d.judge, w = j.winner;
    var rowsSrc = (state.order === "bearFirst" ? D.bias.bearFirst : D.bias.base);
    var runs = rowsSrc && rowsSrc.rows[d.ticker];

    panel.append(h("div", { "class": "card" },
      h("h3", { text: "The judge's verdict" }),
      h("div", { "class": "verdict" }, h("span", { "class": "side-dot " + w }), VERDICT[w] || w),
      h("p", { "class": "reason", text: j.reasoning })));

    var chartHost = h("div", { "class": "chart-card" });
    panel.append(chartHost);
    mountChart(chartHost, {
      title: "Scores out of 10", sub: "One judging run, with bull listed first.",
      draw: function (body, w2) { drawDumbbell(body, w2, j.scores); },
      table: function () {
        return { head: ["Criterion", "Bull", "Bear"], rows: ["evidence", "logic", "responsiveness"].map(function (k) { return [k[0].toUpperCase() + k.slice(1), j.scores.bull[k], j.scores.bear[k]]; }) };
      },
      legend: legend([{ c: "bull", t: "Bull" }, { c: "bear", t: "Bear" }])
    });

    if (runs) {
      panel.append(h("div", { "class": "card" },
        h("h3", { text: "Same debate, judged six times" }),
        h("p", { "class": "sub", text: "The arguments are identical each time. Only the listing order changes. Disagreement here is the judge's own randomness." }),
        h("div", { "class": "runs" }, runDots(runs, "bull"), runDots(runs, "bear"))));
    }

    var c = d.citations.overall, u = d.usage;
    panel.append(h("div", { "class": "card costline" },
      h("span", { text: c.verified + " of " + c.total + " quotes verified" }),
      h("span", { text: u.calls + " model calls" }),
      h("span", { text: Math.round(u.input_tokens / 1000) + "k tokens in" }),
      h("span", { text: "$" + u.cost_usd.toFixed(3) })));
  }

  function renderDebate() {
    var d = debateFor(state.ticker, state.order) || debateFor(state.ticker, "base");
    var t = $("#transcript");
    t.replaceChildren();
    t.append(h("div", {}, h("p", { "class": "round-title", text: d.name + ", 10-K filed " + d.filingDate }),
      h("p", { "class": "muted", style: "font-size:14px", text: d.bullFirst ? "The bull speaks first in each round; the bear replies." : "The bear speaks first in each round; the bull replies." })));
    d.rounds.forEach(function (r) {
      var order = d.bullFirst ? ["bull", "bear"] : ["bear", "bull"];
      t.append(h("div", {}, h("p", { "class": "round-title", text: "Round " + r.round }),
        turnEl(order[0], r[order[0]], true), turnEl(order[1], r[order[1]], false)));
    });
    renderPanel(d);
  }

  renderFilters();
  renderDebate();

