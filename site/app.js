  (function checker() {
    var ck = D.checker, thr = ck.threshold;
    var kinds = [
      ["real", "Real quotes, exactly as the agents wrote them", "Real quotes"],
      ["swap", "The same quotes with one word swapped for “zebra”", "One word swapped"],
      ["drop", "The same quotes with two words dropped", "Two words dropped"],
      ["wrong", "Real quotes checked against another company's filing", "Wrong company's filing"]
    ];
    var host = $("#strip-card");
    function accepted(rows) { return rows.filter(function (r) { return r.s >= thr; }).length; }

    mountChart(host, {
      title: "Match score for " + ck.rows.real.length + " quotes, four ways",
      sub: "Each dot is one quote. The line is the pass mark: dots to its right are accepted.",
      draw: function (body, w) {
        var narrow = w < 560;
        var rowH = narrow ? 112 : 96, top = 8, axisH = 30, padL = 6, padR = 6;
        var H = top + kinds.length * rowH + axisH;
        var x = function (v) { return padL + (v / 100) * (w - padL - padR); };
        var svg = sv("svg", { width: w, height: H, role: "img", "aria-label": "Strip plot of match scores for four kinds of quote" });
        [0, 25, 50, 75, 100].forEach(function (t) {
          svg.append(sv("line", { "class": t === 0 ? "axis-line" : "grid-line", x1: x(t), x2: x(t), y1: top, y2: H - axisH }),
            sv("text", { x: x(t), y: H - 8, "text-anchor": t === 0 ? "start" : t === 100 ? "end" : "middle", text: String(t) }));
        });
        var pts = [];
        kinds.forEach(function (k, i) {
          var y0 = top + i * rowH, rows = ck.rows[k[0]], acc = accepted(rows);
          var accText = pct(acc / rows.length) + " accepted";
          svg.append(sv("text", { x: padL, y: y0 + 18, text: narrow ? k[2] : k[1], style: "fill:var(--ink);font-size:13px;font-weight:600" }),
            narrow
              ? sv("text", { x: padL, y: y0 + 35, text: accText, style: "font-size:12.5px" })
              : sv("text", { x: w - padR, y: y0 + 18, "text-anchor": "end", text: accText, style: "font-size:13px" }));
          rows.forEach(function (r, j) {
            var jitter = ((j * 37) % 100) / 100;
            var cx = x(r.s), cy = y0 + (narrow ? 50 : 34) + jitter * 48;
            svg.append(sv("circle", { cx: cx, cy: cy, r: 4, style: "fill:var(--ink-2);opacity:.5" }));
            pts.push({ cx: cx, cy: cy, r: r });
          });
        });
        svg.append(sv("line", { x1: x(thr), x2: x(thr), y1: top, y2: H - axisH, stroke: "var(--ink)", "stroke-width": 1.5 }),
          sv("text", { x: x(thr) - 6, y: H - axisH + 12, "text-anchor": "end", text: "pass mark " + thr, style: "fill:var(--ink);font-weight:650" }));
        var marker = sv("circle", { r: 7, fill: "none", stroke: "var(--ink)", "stroke-width": 2, visibility: "hidden" });
        svg.append(marker);
        svg.addEventListener("pointermove", function (e) {
          var box = svg.getBoundingClientRect(), mx = e.clientX - box.left, my = e.clientY - box.top;
          var best = null, bd = 16 * 16;
          pts.forEach(function (p) { var dd = (p.cx - mx) * (p.cx - mx) + (p.cy - my) * (p.cy - my); if (dd < bd) { bd = dd; best = p; } });
          if (!best) { marker.setAttribute("visibility", "hidden"); hideTip(); return; }
          marker.setAttribute("cx", best.cx); marker.setAttribute("cy", best.cy); marker.setAttribute("visibility", "visible");
          showTip([{ t: "Match " + best.r.s + " of 100", c: "tv" }, { t: base[best.r.t].name }, { t: "“" + best.r.q + "”", c: "tq" }], e.clientX, e.clientY);
        });
        svg.addEventListener("pointerleave", function () { marker.setAttribute("visibility", "hidden"); hideTip(); });
        body.append(svg);
      },
      table: function () {
        return { head: ["Kind of quote", "Quotes", "Accepted", "Lowest score", "Highest score"],
          rows: kinds.map(function (k) {
            var rows = ck.rows[k[0]], sc = rows.map(function (r) { return r.s; });
            return [k[1], rows.length, accepted(rows) + " (" + pct(accepted(rows) / rows.length) + ")", Math.min.apply(null, sc), Math.max.apply(null, sc)];
          }) };
      }
    });

    var rate = function (k) { return accepted(ck.rows[k]) / ck.rows[k].length; };
    host.after(h("p", { "class": "takeaway",
      text: "A real quote passes " + pct(rate("real")) + " of the time. Swap one word and it still passes " + pct(rate("swap")) +
        ". Drop two words and it passes " + pct(rate("drop")) + ". A real quote from the wrong company passes " + pct(rate("wrong")) +
        ". The checker forgives small slips but not invented or misplaced quotes." }));
  })();

